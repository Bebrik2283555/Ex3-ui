package dnsresolver

import (
	"net"
	"strings"
	"testing"

	"golang.org/x/net/dns/dnsmessage"
)

func TestExtractIPsReturnsEveryAnswer(t *testing.T) {
	name := dnsmessage.MustNewName("chatgpt.com.")
	msg := dnsmessage.Message{
		Header:    dnsmessage.Header{Response: true},
		Questions: []dnsmessage.Question{{Name: name, Type: dnsmessage.TypeA, Class: dnsmessage.ClassINET}},
		Answers: []dnsmessage.Resource{
			{Header: dnsmessage.ResourceHeader{Name: name, Type: dnsmessage.TypeA, Class: dnsmessage.ClassINET}, Body: &dnsmessage.AResource{A: [4]byte{157, 22, 178, 170}}},
			{Header: dnsmessage.ResourceHeader{Name: name, Type: dnsmessage.TypeA, Class: dnsmessage.ClassINET}, Body: &dnsmessage.AResource{A: [4]byte{176, 12, 72, 184}}},
			// A duplicate must not produce a second probe.
			{Header: dnsmessage.ResourceHeader{Name: name, Type: dnsmessage.TypeA, Class: dnsmessage.ClassINET}, Body: &dnsmessage.AResource{A: [4]byte{176, 12, 72, 184}}},
		},
	}
	raw, err := msg.Pack()
	if err != nil {
		t.Fatal(err)
	}
	ips, err := extractIPs(raw)
	if err != nil {
		t.Fatal(err)
	}
	if len(ips) != 2 {
		t.Fatalf("got %v, want 2 unique addresses", ips)
	}
	if ips[0] != net.IPv4(157, 22, 178, 170).String() {
		t.Errorf("first address = %s", ips[0])
	}
}

func TestExtractIPsRejectsEmptyAnswer(t *testing.T) {
	name := dnsmessage.MustNewName("chatgpt.com.")
	msg := dnsmessage.Message{
		Header:    dnsmessage.Header{Response: true},
		Questions: []dnsmessage.Question{{Name: name, Type: dnsmessage.TypeA, Class: dnsmessage.ClassINET}},
	}
	raw, _ := msg.Pack()
	if _, err := extractIPs(raw); err == nil {
		t.Fatal("expected an error when no A record is present")
	}
}

func TestNeedsRegionGate(t *testing.T) {
	gated := []string{"chatgpt.com", "ab.chatgpt.com", "openai.com", "api.openai.com", "claude.ai", "anthropic.com"}
	for _, d := range gated {
		if !needsRegionGate(d) {
			t.Errorf("%s must be region gated", d)
		}
	}
	// Static asset hosts keep working from any country.
	for _, d := range []string{"oaistatic.com", "cdn.oaistatic.com", "files.oaiusercontent.com", "gemini.google.com"} {
		if needsRegionGate(d) {
			t.Errorf("%s must not be region gated", d)
		}
	}
}

// The zapret block lives in the same file; rewriting the SmartDNS block must
// leave it intact and vice versa.
func TestStripHostsBlockKeepsZapretBlock(t *testing.T) {
	content := `127.0.0.1 localhost

# ========================================================
# Auto-generated by Ex3-UI SmartDNS (Geo-unblock)
# Do not edit manually - managed automatically
176.12.72.184 chatgpt.com
# ========================================================

# ========================================================
# Auto-generated by Ex3-UI zapret (GitHub/Discord bypass)
# Do not edit manually - managed automatically
# ========================================================
140.82.121.3 github.com
# ========================================================
`
	cleaned := stripHostsBlock(content)
	if strings.Contains(cleaned, "chatgpt.com") {
		t.Errorf("SmartDNS entry survived:\n%s", cleaned)
	}
	if !strings.Contains(cleaned, "140.82.121.3 github.com") {
		t.Errorf("zapret block was removed:\n%s", cleaned)
	}
	if !strings.Contains(cleaned, "127.0.0.1 localhost") {
		t.Errorf("localhost was removed:\n%s", cleaned)
	}
}
