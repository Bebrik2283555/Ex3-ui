// GetDefaultDomains returns a fresh copy of the default domain list.
func GetDefaultDomains() []string {
	return append([]string{}, defaultDomains...)
}

func hasLegacyDefaults(domains []string) bool {
	legacy := map[string]bool{
		"canva.com":        true,
		"spotify.com":      true,
		"open.spotify.com": true,
		"notion.so":        true,
	}
	for _, d := range domains {
		if legacy[d] {
			return true
		}
	}
	return false
}

// Settings stores user configuration for the DNS resolver.
type Settings struct {
	Enabled       bool     `json:"enabled"`
	DnsServer     string   `json:"dnsServer"`
	IntervalHours int      `json:"intervalHours"`
	Domains       []string `json:"domains"`
}

// DnsTestResult represents the result of checking connectivity to a DNS server.
type DnsTestResult struct {
	Success   bool   `json:"success"`
	LatencyMs int64  `json:"latencyMs"`
	IP        string `json:"ip,omitempty"`
	Server    string `json:"server"`
	Error     string `json:"error,omitempty"`
}

// ResolvedEntry represents one resolved domain-to-IP mapping.
type ResolvedEntry struct {
	Domain    string `json:"domain"`
	IP        string `json:"ip"`
	Status    string `json:"status"`
	Region    string `json:"region,omitempty"`
	LatencyMs int64  `json:"latencyMs,omitempty"`
	Error     string `json:"error,omitempty"`
}

// Status represents the runtime status and current entries of DNS resolver.
type Status struct {
	Enabled        bool            `json:"enabled"`
	DnsServer      string          `json:"dnsServer"`
	IntervalHours  int             `json:"intervalHours"`
	Domains        []string        `json:"domains"`
	DefaultDomains []string        `json:"defaultDomains"`
	Running        bool            `json:"running"`
	LastRun        string          `json:"lastRun"`
	LastResult     string          `json:"lastResult"`
	LastError      string          `json:"lastError"`
	Entries        []ResolvedEntry `json:"entries"`
}

type persistedState struct {
	Settings   Settings        `json:"settings"`
	LastRun    string          `json:"lastRun"`
	LastResult string          `json:"lastResult"`
	LastError  string          `json:"lastError"`
	Entries    []ResolvedEntry `json:"entries"`
}

var (
	mu             sync.Mutex
	settings       Settings
	running        bool
	lastRun        string
	lastResult     string
	lastError      string
	currentEntries []ResolvedEntry
	onCronUpdate   func(intervalHours int, enabled bool)
)

// RegisterCronUpdateHook sets the callback invoked when settings change.
func RegisterCronUpdateHook(hook func(intervalHours int, enabled bool)) {
	mu.Lock()
	defer mu.Unlock()
	onCronUpdate = hook
}

func configPath() string {
	return filepath.Join(config.GetDBFolderPath(), "dns_resolver.json")
}

func init() {
	settings = Settings{
		Enabled:       false,
		DnsServer:     defaultDnsServer,
		IntervalHours: defaultIntervalHours,
		Domains:       append([]string{}, defaultDomains...),
	}
	loadState()
}

func loadState() {
	data, err := os.ReadFile(configPath())
	if err != nil {
		return
	}
	var state persistedState
	if err := json.Unmarshal(data, &state); err != nil {
		return
	}
	if state.Settings.DnsServer == "" {
		state.Settings.DnsServer = defaultDnsServer
	}
	if state.Settings.IntervalHours <= 0 {
		state.Settings.IntervalHours = defaultIntervalHours
	}
	if len(state.Settings.Domains) == 0 || hasLegacyDefaults(state.Settings.Domains) {
		state.Settings.Domains = append([]string{}, defaultDomains...)
	}
	settings = state.Settings
	lastRun = state.LastRun
	lastResult = state.LastResult
	lastError = state.LastError
	currentEntries = state.Entries
}

func saveState() {
	state := persistedState{
		Settings:   settings,
		LastRun:    lastRun,
		LastResult: lastResult,
		LastError:  lastError,
		Entries:    currentEntries,
	}
	data, err := json.MarshalIndent(state, "", "  ")
	if err != nil {
		return
	}
	_ = os.WriteFile(configPath(), data, 0o644)
}

// GetStatus returns the current status and settings.
func GetStatus() Status {
	mu.Lock()
	defer mu.Unlock()
	return Status{
		Enabled:        settings.Enabled,
		DnsServer:      settings.DnsServer,
		IntervalHours:  settings.IntervalHours,
		Domains:        append([]string{}, settings.Domains...),
		DefaultDomains: append([]string{}, defaultDomains...),
		Running:        running,
		LastRun:        lastRun,
		LastResult:     lastResult,
		LastError:      lastError,
		Entries:        append([]ResolvedEntry{}, currentEntries...),
	}
}

// GetSettings returns current configuration settings.
func GetSettings() Settings {
	mu.Lock()
	defer mu.Unlock()
	return Settings{
		Enabled:       settings.Enabled,
		DnsServer:     settings.DnsServer,
		IntervalHours: settings.IntervalHours,
		Domains:       append([]string{}, settings.Domains...),
	}
}

// SaveSettings updates configuration and updates scheduled cron job.
func SaveSettings(newSettings Settings) error {
	mu.Lock()
	if newSettings.DnsServer == "" {
		newSettings.DnsServer = defaultDnsServer
	}
	if newSettings.IntervalHours < 1 {
		newSettings.IntervalHours = 1
	} else if newSettings.IntervalHours > 168 {
		newSettings.IntervalHours = 168
	}
	if len(newSettings.Domains) == 0 {
		newSettings.Domains = append([]string{}, defaultDomains...)
	}
	settings = newSettings
	saveState()
	hook := onCronUpdate
	enabled := settings.Enabled
	interval := settings.IntervalHours
	mu.Unlock()

	if hook != nil {
		hook(interval, enabled)
	}

	if enabled {
		go func() {
			_ = Resolve(context.Background())
		}()
	} else {
		// Clean up the block from /etc/hosts if disabled
		_ = removeHostsBlock()
	}
	return nil
}

// SaveDomains updates only the domain list.
func SaveDomains(domains []string) error {
	mu.Lock()
	cleaned := make([]string, 0, len(domains))
	for _, d := range domains {
		d = strings.TrimSpace(d)
		if d != "" && !strings.HasPrefix(d, "#") {
			cleaned = append(cleaned, d)
		}
	}
	if len(cleaned) == 0 {
		cleaned = append([]string{}, defaultDomains...)
	}
	settings.Domains = cleaned
	saveState()
	enabled := settings.Enabled
	mu.Unlock()

	if enabled {
		go func() {
			_ = Resolve(context.Background())
		}()
	}
	return nil
}

// Resolve queries the DNS server for all domains and writes results to /etc/hosts.
func Resolve(ctx context.Context) error {
	mu.Lock()
	if running {
		mu.Unlock()
		return fmt.Errorf("resolution already in progress")
	}
	running = true
	dnsSrv := settings.DnsServer
	domainList := append([]string{}, settings.Domains...)
	mu.Unlock()

	defer func() {
		mu.Lock()
		running = false
		mu.Unlock()
	}()

	// Hard timeout on the overall resolution process so it never hangs indefinitely.
	// Verification dials every candidate, so this allows more than a bare query.
	ctx, cancel := context.WithTimeout(ctx, 45*time.Second)
	defer cancel()

	logger.Infof("SmartDNS: resolving %d domains via %s", len(domainList), dnsSrv)

	type queryResult struct {
		index  int
		domain string
		probe  probe
		err    error
	}

	results := make([]queryResult, len(domainList))
	sem := make(chan struct{}, 6) // parallel concurrency
	var wg sync.WaitGroup

	for i, d := range domainList {
		domain := strings.TrimSpace(d)
		if domain == "" {
			continue
		}
		wg.Add(1)
		go func(idx int, dom string) {
			defer wg.Done()
			select {
			case sem <- struct{}{}:
				defer func() { <-sem }()
			case <-ctx.Done():
				results[idx] = queryResult{index: idx, domain: dom, err: ctx.Err()}
				return
			}

			p, err := resolveBest(ctx, dnsSrv, dom)
			results[idx] = queryResult{index: idx, domain: dom, probe: p, err: err}
		}(i, domain)
	}

	wg.Wait()

	mu.Lock()
	previous := make(map[string]ResolvedEntry, len(currentEntries))
	for _, e := range currentEntries {
		if e.IP != "" {
			previous[e.Domain] = e
		}
	}
	mu.Unlock()

	entries := make([]ResolvedEntry, 0, len(domainList))
	successCount := 0
	staleCount := 0

	for i, dom := range domainList {
		dom = strings.TrimSpace(dom)
		if dom == "" {
			continue
		}
		res := results[i]
		if res.err != nil {
			// A broken or emptied block would break a domain that still worked
			// on the previous pass, so keep the last known-good address.
			if old, ok := previous[dom]; ok {
				staleCount++
				logger.Warningf("SmartDNS: probe failed for %s (%v), keeping %s", dom, res.err, old.IP)
				entries = append(entries, ResolvedEntry{
					Domain:    dom,
					IP:        old.IP,
					Status:    "STALE",
					Region:    old.Region,
					LatencyMs: old.LatencyMs,
					Error:     res.err.Error(),
				})
				continue
			}
			logger.Warningf("SmartDNS: failed to resolve %s: %v", dom, res.err)
			entries = append(entries, ResolvedEntry{
				Domain: dom,
				Status: "FAILED",
				Error:  res.err.Error(),
			})
			continue
		}
		successCount++
		entries = append(entries, ResolvedEntry{
			Domain:    dom,
			IP:        res.probe.IP,
			Status:    "OK",
			Region:    res.probe.Region,
			LatencyMs: res.probe.Latency.Milliseconds(),
		})
	}

	nowStr := time.Now().Format("02.01.2006 15:04:05")
	var resultStr, errStr string
	switch {
	case successCount == len(domainList):
		resultStr = fmt.Sprintf("Успешно: проверено %d из %d доменов", successCount, len(domainList))
	case successCount > 0:
		resultStr = fmt.Sprintf("Частично: проверено %d из %d доменов", successCount, len(domainList))
		errStr = fmt.Sprintf("Не удалось проверить %d доменов", len(domainList)-successCount)
	default:
		resultStr = "Ошибка: не удалось проверить домены"
		errStr = "Ни один домен не ответил корректно через указанный DNS-сервер (таймаут, неверный сертификат или заблокированный регион)"
	}
	if staleCount > 0 && errStr == "" {
		resultStr = fmt.Sprintf("%s (оставлен предыдущий IP для %d)", resultStr, staleCount)
	}

	mu.Lock()
	lastRun = nowStr
	lastResult = resultStr
	lastError = errStr
	currentEntries = entries
	saveState()
	mu.Unlock()

	// Write to /etc/hosts
	if err := updateHostsBlock(entries); err != nil {
		logger.Warningf("SmartDNS: failed to update /etc/hosts: %v", err)
		return err
	}
	logger.Infof("SmartDNS: updated /etc/hosts with %d domains", successCount)
	return nil
}

// TestDNS probes the specified DNS server with a test query (chatgpt.com) and returns latency.
func TestDNS(server string) DnsTestResult {
	server = strings.TrimSpace(server)
	if server == "" {
		mu.Lock()
		server = settings.DnsServer
		mu.Unlock()
	}
	if server == "" {
		server = defaultDnsServer
	}

	start := time.Now()
	ctx, cancel := context.WithTimeout(context.Background(), 3500*time.Millisecond)
	defer cancel()

	ip, err := resolveOne(ctx, server, "chatgpt.com")
	latency := time.Since(start).Milliseconds()

	if err != nil {
		return DnsTestResult{
			Success:   false,
			LatencyMs: 0,
			Server:    server,
			Error:     err.Error(),
		}
	}

	return DnsTestResult{
		Success:   true,
		LatencyMs: latency,
		IP:        ip,
		Server:    server,
	}
}

func resolveOne(ctx context.Context, server, domain string) (string, error) {
	ips, err := resolveAll(ctx, server, domain)
	if err != nil {
		return "", err
	}
	return ips[0], nil
}

// resolveAll returns every A record of domain, not just the first one: the
// geo-unblock proxies behind the same name differ in health and region, so the
// caller needs the whole set to pick a working address.
func resolveAll(ctx context.Context, server, domain string) ([]string, error) {
	if strings.HasPrefix(server, "https://") || strings.HasPrefix(server, "http://") {
		return resolveDoH(ctx, server, domain)
	}
	return resolveUDP(ctx, server, domain)
}

func resolveDoH(ctx context.Context, endpoint, domain string) ([]string, error) {
	reqMsg := buildDnsQuery(domain)
	raw, err := reqMsg.Pack()
	if err != nil {
		return nil, fmt.Errorf("pack dns query: %w", err)
	}

	httpReq, err := http.NewRequestWithContext(ctx, http.MethodPost, endpoint, bytes.NewReader(raw))
	if err != nil {
		return nil, fmt.Errorf("create doh request: %w", err)
	}
	httpReq.Header.Set("Content-Type", "application/dns-message")
	httpReq.Header.Set("Accept", "application/dns-message")

	tr := &http.Transport{
		Proxy: http.ProxyFromEnvironment,
		DialContext: (&net.Dialer{
			Timeout:   2 * time.Second,
			KeepAlive: 30 * time.Second,
		}).DialContext,
		TLSHandshakeTimeout:   2 * time.Second,
		ResponseHeaderTimeout: 3 * time.Second,
		ExpectContinueTimeout: 1 * time.Second,
	}
	client := &http.Client{
		Transport: tr,
		Timeout:   3500 * time.Millisecond,
	}
	resp, err := client.Do(httpReq)
	if err != nil {
		return nil, fmt.Errorf("doh request: %w", err)
	}
	defer resp.Body.Close()

	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("doh status %d", resp.StatusCode)
	}

	body, err := io.ReadAll(io.LimitReader(resp.Body, 64*1024))
	if err != nil {
		return nil, fmt.Errorf("read doh response: %w", err)
	}

	return extractIPs(body)
}

func resolveUDP(ctx context.Context, server, domain string) ([]string, error) {
	target := server
	if !strings.Contains(target, ":") {
		target = net.JoinHostPort(target, "53")
	}

	reqMsg := buildDnsQuery(domain)
	raw, err := reqMsg.Pack()
	if err != nil {
		return nil, fmt.Errorf("pack dns query: %w", err)
	}

	d := net.Dialer{Timeout: 2500 * time.Millisecond}
	conn, err := d.DialContext(ctx, "udp", target)
	if err != nil {
		return nil, fmt.Errorf("udp dial: %w", err)
	}
	defer conn.Close()

	_ = conn.SetDeadline(time.Now().Add(2500 * time.Millisecond))
	if _, err := conn.Write(raw); err != nil {
		return nil, fmt.Errorf("udp write: %w", err)
	}

	buf := make([]byte, 4096)
	n, err := conn.Read(buf)
	if err != nil {
		return nil, fmt.Errorf("udp read: %w", err)
	}

	return extractIPs(buf[:n])
}

func buildDnsQuery(domain string) dnsmessage.Message {
	var id [2]byte
	_, _ = rand.Read(id[:])

	name, err := dnsmessage.NewName(strings.TrimSuffix(domain, ".") + ".")
	if err != nil {
		name = dnsmessage.MustNewName("localhost.")
	}

	return dnsmessage.Message{
		Header: dnsmessage.Header{
			ID:               binary.BigEndian.Uint16(id[:]),
			RecursionDesired: true,
		},
		Questions: []dnsmessage.Question{
			{
				Name:  name,
				Type:  dnsmessage.TypeA,
				Class: dnsmessage.ClassINET,
			},
		},
	}
}

// extractIPs collects every unique A record in a DNS response.
func extractIPs(data []byte) ([]string, error) {
	var msg dnsmessage.Message
	if err := msg.Unpack(data); err != nil {
		return nil, fmt.Errorf("unpack dns: %w", err)
	}

	seen := make(map[string]bool, len(msg.Answers))
	ips := make([]string, 0, len(msg.Answers))
	for _, ans := range msg.Answers {
		if a, ok := ans.Body.(*dnsmessage.AResource); ok {
			ip := net.IP(a.A[:]).String()
			if !seen[ip] {
				seen[ip] = true
				ips = append(ips, ip)
			}
		}
	}
	if len(ips) == 0 {
		return nil, fmt.Errorf("no A record in response")
	}
	return ips, nil
}

// updateHostsBlock writes or updates the 3-line comment separated block in /etc/hosts.
func updateHostsBlock(entries []ResolvedEntry) error {
	if runtime.GOOS != "linux" {
		return nil
	}

	var validLines []string
	for _, e := range entries {
		if e.IP != "" && e.Domain != "" {
			validLines = append(validLines, fmt.Sprintf("%s %s", e.IP, e.Domain))
		}
	}

	existing, _ := os.ReadFile(hostsFilePath)
	text := string(existing)

	cleaned := stripHostsBlock(text)

	if len(validLines) == 0 {
		return os.WriteFile(hostsFilePath, []byte(cleaned), 0o644)
	}

	var sb strings.Builder
	sb.WriteString(strings.TrimRight(cleaned, "\n"))
	if sb.Len() > 0 {
		sb.WriteString("\n\n")
	}
	sb.WriteString(blockHeader)
	sb.WriteString("\n")
	for _, line := range validLines {
		sb.WriteString(line)
		sb.WriteString("\n")
	}
	sb.WriteString(blockFooter)
	sb.WriteString("\n")

	return os.WriteFile(hostsFilePath, []byte(sb.String()), 0o644)
}

func removeHostsBlock() error {
	if runtime.GOOS != "linux" {
		return nil
	}
	existing, err := os.ReadFile(hostsFilePath)
	if err != nil {
		return nil
	}
	cleaned := stripHostsBlock(string(existing))
	return os.WriteFile(hostsFilePath, []byte(cleaned), 0o644)
}

// stripHostsBlock removes the panel's SmartDNS block. The markers are matched
// as whole lines inside a complete header/footer pair, and an unterminated
// header leaves the file untouched: a stray comment must never truncate the
// rest of /etc/hosts.
func stripHostsBlock(content string) string {
	lines := strings.SplitAfter(content, "\n")
	start, end := hostsBlockRange(lines)
	if start < 0 {
		return content
	}
	var sb strings.Builder
	sb.Grow(len(content))
	for i, line := range lines {
		if i >= start && i < end {
			continue
		}
		sb.WriteString(line)
	}
	return sb.String()
}

// hostsBlockRange returns the half-open line range of the panel's block, or
// (-1, -1) when the file holds no complete block.
func hostsBlockRange(lines []string) (int, int) {
	for i, line := range lines {
		if !isHostsBlockMarker(line) {
			continue
		}
		if i == 0 || !isHostsSeparator(lines[i-1]) {
			continue
		}
		if i+1 >= len(lines) || !strings.HasPrefix(strings.TrimSpace(lines[i+1]), "# Do not edit manually") {
			continue
		}
		for j := i + 2; j < len(lines); j++ {
			if isHostsSeparator(lines[j]) {
				return i - 1, j + 1
			}
		}
		// Header without its footer: the file was edited or truncated, so do
		// not guess where user content starts.
		return -1, -1
	}
	return -1, -1
}

func isHostsBlockMarker(line string) bool {
	trimmed := strings.TrimSpace(line)
	return strings.HasPrefix(trimmed, "# Auto-generated by Ex3-UI SmartDNS") ||
		strings.HasPrefix(trimmed, "# Auto-generated by Ex3-UI DNS Resolver")
}

func isHostsSeparator(line string) bool {
	return strings.TrimSpace(line) == blockFooter
}
